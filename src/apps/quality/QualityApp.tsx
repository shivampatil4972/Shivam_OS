"use client";

import { CircleAlert, CircleCheck, CircleDashed, CircleMinus, CircleX } from "lucide-react";
import { useEffect, useState } from "react";
import { Badge } from "@/design/ui";
import { qualityReportSchema, type CheckStatus, type QualityReport } from "@/lib/qualityReport";
import { AppScroll } from "../shared";

const STATUS: Record<CheckStatus, { label: string; tone: "success" | "danger" | "warning" | "neutral"; Icon: typeof CircleCheck; color: string }> = {
  passed: { label: "Passed", tone: "success", Icon: CircleCheck, color: "text-success" },
  failed: { label: "Failed", tone: "danger", Icon: CircleX, color: "text-danger" },
  warning: { label: "Passed with warnings", tone: "warning", Icon: CircleAlert, color: "text-warning" },
  "not-run": { label: "Not run", tone: "neutral", Icon: CircleDashed, color: "text-subtle" },
  unavailable: { label: "Unavailable", tone: "neutral", Icon: CircleMinus, color: "text-subtle" },
};

function when(iso: string | null) {
  if (!iso) return "—";
  const d = new Date(iso);
  return `${d.toLocaleDateString("en-GB", { day: "numeric", month: "short", year: "numeric" })}, ${d.toLocaleTimeString("en-GB", { hour: "2-digit", minute: "2-digit", timeZone: "UTC" })} UTC`;
}

export default function QualityApp() {
  const [report, setReport] = useState<QualityReport | null>(null);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    fetch("/reports/quality-report.json", { cache: "no-store" })
      .then((r) => {
        if (!r.ok) {
          void r.body?.cancel();
          throw new Error(`No report found (HTTP ${r.status})`);
        }
        return r.json();
      })
      .then((json) => {
        const parsed = qualityReportSchema.safeParse(json);
        if (!parsed.success) throw new Error("The report file is malformed.");
        setReport(parsed.data);
      })
      .catch((e: Error) => setError(e.message));
  }, []);

  const counts = report?.checks.reduce<Record<CheckStatus, number>>((acc, c) => ({ ...acc, [c.status]: (acc[c.status] ?? 0) + 1 }), { passed: 0, failed: 0, warning: 0, "not-run": 0, unavailable: 0 });

  return (
    <AppScroll wide>
      <h3 className="font-display text-2xl font-semibold text-fg">Quality Control Center</h3>
      <p className="mt-1 max-w-3xl text-[14px] text-muted">
        Results of this site&apos;s own checks, generated by <code className="font-mono text-[13px]">npm run qc</code>. Each entry shows when it actually ran; anything not executed is shown as “Not run”, never as passing.
      </p>

      {error && (
        <p role="alert" className="card mt-5 p-4 text-[14px] text-fg">
          {error}. Quality results are only shown when a real report exists.
        </p>
      )}
      {!report && !error && (
        <p className="mt-5 text-[14px] text-muted" role="status">
          Loading the latest report…
        </p>
      )}

      {report && counts && (
        <>
          <dl className="mt-5 grid grid-cols-2 gap-3 md:grid-cols-5">
            {(["passed", "warning", "failed", "not-run", "unavailable"] as CheckStatus[]).map((s) => {
              const { Icon, color, label } = STATUS[s];
              return (
                <div key={s} className="card p-3">
                  <dt className="flex items-center gap-1.5 text-[12px] text-subtle">
                    <Icon className={`size-3.5 ${color}`} aria-hidden /> {label}
                  </dt>
                  <dd className="font-display text-2xl font-semibold text-fg">{counts[s]}</dd>
                </div>
              );
            })}
          </dl>
          <p className="mt-3 text-[12.5px] text-subtle">
            Report generated {when(report.generatedAt)} · commit {report.commit ?? "uncommitted"} · Node {report.environment.node} on {report.environment.platform}
            {report.environment.browser ? ` · ${report.environment.browser}` : ""}
          </p>

          <ul className="mt-5 space-y-3">
            {report.checks.map((c) => {
              const { Icon, color, tone, label } = STATUS[c.status];
              return (
                <li key={c.id} className="card p-4">
                  <div className="flex flex-wrap items-center gap-2">
                    <Icon className={`size-5 ${color}`} aria-hidden />
                    <h4 className="font-semibold text-fg">{c.title}</h4>
                    <Badge tone={tone}>{label}</Badge>
                    <span className="ml-auto text-[12px] text-subtle">
                      {c.ranAt ? `Ran ${when(c.ranAt)}` : "Not executed"}
                      {c.durationMs !== null ? ` · ${(c.durationMs / 1000).toFixed(1)} s` : ""}
                    </span>
                  </div>
                  <p className="mt-1.5 text-[14px] text-fg">{c.summary}</p>
                  {c.metrics.length > 0 && (
                    <dl className="mt-2 flex flex-wrap gap-2">
                      {c.metrics.map((m) => (
                        <div key={m.label} className="rounded-lg bg-sunken px-2.5 py-1 text-[12.5px]">
                          <dt className="inline text-subtle">{m.label}: </dt>
                          <dd className="inline font-medium text-fg tabular-nums">{m.value}</dd>
                        </div>
                      ))}
                    </dl>
                  )}
                  {c.details.length > 0 && (
                    <details className="mt-2 text-[12.5px] text-muted">
                      <summary className="cursor-pointer text-fg">Details ({c.details.length})</summary>
                      <ul className="mt-1.5 space-y-0.5 font-mono text-[12px]">
                        {c.details.map((d) => (
                          <li key={d} className="break-words">
                            {d}
                          </li>
                        ))}
                      </ul>
                    </details>
                  )}
                  <p className="mt-2 font-mono text-[11.5px] text-subtle">$ {c.command}</p>
                </li>
              );
            })}
          </ul>
        </>
      )}
    </AppScroll>
  );
}
